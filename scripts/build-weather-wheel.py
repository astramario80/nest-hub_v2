import xml.etree.ElementTree as E,json,re,pathlib,sys
source=pathlib.Path(sys.argv[1]); root=E.parse(source).getroot(); E.register_namespace('', 'http://www.w3.org/2000/svg')
ns='{http://www.w3.org/2000/svg}'; items=[]; family=''; middle=''; children=list(root)
for i,node in enumerate(children):
 if node.tag!=ns+'path' or i+1>=len(children) or children[i+1].tag!=ns+'text': continue
 text=children[i+1]; label=' '.join(text.itertext()).strip().title(); size=int(text.get('font-size','0'))
 if size==20: family=label; middle=''; chain=[label]
 elif size==13: middle=label; chain=[family,label]
 else: chain=[family,middle,label]
 key='e'+str(len(items)); item={'id':key,'label':label,'family':family,'answer':' / '.join(x for x in chain if x),'charged':family in ['Sad','Anger','Fear','Disgust']};items.append(item)
 group=E.Element(ns+'g',{'data-emotion':key,'role':'button','tabindex':'-1','aria-label':item['answer']})
 at=list(root).index(node);root.remove(node);root.remove(text);group.extend([node,text]);root.insert(at,group)
root.set('role','img');root.set('aria-label','Emotion sensation wheel by Lindsay Braman');root.attrib.pop('width',None);root.attrib.pop('height',None)
pathlib.Path('assets/emotional-check-in.svg').write_text(E.tostring(root,encoding='unicode'))
pathlib.Path('assets/weather-emotions.json').write_text(json.dumps(items,ensure_ascii=False))
pathlib.Path('google-spinner/WeatherEmotions.js').write_text('// Generated by scripts/build-weather-wheel.py from the supplied wheel.\nconst WEATHER_EMOTIONS = '+json.dumps(items,ensure_ascii=False)+';\n')
print(len(items),'segments;',sorted(set(x['family'] for x in items)))
