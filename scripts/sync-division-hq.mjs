import fs from 'node:fs';
import {JSDOM} from 'jsdom';

// Reuse the existing tools and descriptions without maintaining a second copy.
const documentFor=path=>new JSDOM(fs.readFileSync(path,'utf8')).window.document;
const leadership=documentFor('leadership.html').querySelector('main.leadership-page');
leadership.querySelector('.leadership-hero-right')?.remove();
const title=leadership.querySelector('h1');title.outerHTML='<h2>Team Lookup</h2>';
leadership.querySelector('#manager-tools').setAttribute('data-hq-hide','');
const jobs=documentFor('leadership-jobs.html').querySelector('.jobs-list');
jobs.querySelectorAll('.job-apply').forEach(link=>link.remove());
const hiring=documentFor('hiring.html').querySelector('#manager-hiring');
const exports={HQ_LOOKUP_HTML:leadership.innerHTML,HQ_JOBS_HTML:jobs.outerHTML,HQ_HIRING_HTML:hiring.outerHTML};
fs.writeFileSync('lib/division-hq-content.mjs','// Generated by scripts/sync-division-hq.mjs from the existing NEST pages.\n'+Object.entries(exports).map(([name,html])=>`export const ${name} = ${JSON.stringify(html)};`).join('\n')+'\n');
